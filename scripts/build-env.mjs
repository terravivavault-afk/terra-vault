// Generates js/env.js from environment variables so each deployment (Vercel, GitHub Pages,
// local) can point at its own Supabase project and public URL without editing source.
// Only PUBLIC values belong here: the Supabase URL and the *anon* key. Never the service_role key.
import { writeFileSync } from 'node:fs';

const keys = ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'SITE_URL'];
const env = {};
for (const k of keys) {
  const v = (process.env[k] || process.env[`VITE_${k}`] || process.env[`NEXT_PUBLIC_${k}`] || '').trim();
  if (v) env[k] = v;
}
if (process.env.SUPABASE_SERVICE_ROLE_KEY && Object.values(env).includes(process.env.SUPABASE_SERVICE_ROLE_KEY)) {
  console.error('Refusing to build: a service_role key was supplied as a public value.');
  process.exit(1);
}
if (!env.SITE_URL && process.env.VERCEL_PROJECT_PRODUCTION_URL && process.env.VERCEL_ENV === 'production') {
  env.SITE_URL = `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`;
} else if (!env.SITE_URL && process.env.VERCEL_URL) {
  env.SITE_URL = `https://${process.env.VERCEL_URL}`;
}
writeFileSync('js/env.js', `// Generated by scripts/build-env.mjs — do not edit.\nwindow.__TV_ENV__ = ${JSON.stringify(env, null, 2)};\n`);
console.log('js/env.js written with:', Object.keys(env).join(', ') || '(defaults)');
